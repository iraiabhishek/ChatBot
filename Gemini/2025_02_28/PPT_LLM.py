import os

import google.generativeai as genai
from dotenv import load_dotenv
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_google_genai import ChatGoogleGenerativeAI
from pptx import Presentation

# # Configure Gemini API
# api_key = API_KEY
# genai.configure(api_key=api_key)

# Load environment variables from .env file
load_dotenv()

# Get API key from environment variable
api_key = os.getenv("GEMINI_API_KEY")


# Initialize the Gemini model
llm = ChatGoogleGenerativeAI(model="gemini-1.5-flash", google_api_key=api_key)

# System message
messages = [
    SystemMessage(
        content="You are a helpful assistant that generates structured content with bullet points suitable for presentations.")
]


def create_ppt(title, response, ppt_filename="generated_presentation.pptx"):
    """Creates a PowerPoint presentation from LLM response."""
    prs = Presentation()

    # Add Title Slide
    slide_layout = prs.slide_layouts[0]  # Title Slide Layout
    slide = prs.slides.add_slide(slide_layout)
    slide.shapes.title.text = title
    slide.placeholders[1].text = "Generated by AI"

    # Process response into bullet points
    content = response.content.split("\n")

    for item in content:
        if item.strip():  # Skip empty lines
            slide_layout = prs.slide_layouts[1]  # Title and Content Layout
            slide = prs.slides.add_slide(slide_layout)
            slide.shapes.title.text = "Slide"
            slide.placeholders[1].text = item  # Add text to slide

    # Save PowerPoint file
    prs.save(ppt_filename)
    print(f"PPT saved as {ppt_filename}")


print("Ask a question related to structured content. Type 'exit' to quit.")

while True:
    user_input = input("You: ")
    if user_input.lower() == "exit":
        print("Goodbye!")
        break

    messages.append(HumanMessage(content=user_input))  # Add user input to history

    response = llm.invoke(messages)  # Get model response

    print(f"Model Response:\n{response.content}")  # Show raw response

    create_ppt(user_input, response)  # Create PowerPoint

    messages.append(SystemMessage(content=response.content))  # Store response
